"""gdbrpc CLI: install / status / new-plugin.

This runs in the *venv* Python, never inside GDB — so this module must
not import anything that imports gdb (queue.py / bootstrap.py etc.).
"""

import argparse
import json
import os
import sys
import sysconfig
import time
from pathlib import Path

from . import __version__
from .config import (
    CONFIG_DIR,
    DEFAULT_PORT,
    DEFAULT_PLUGIN_DIR,
    ENV_FILE,
    SHIM_FILE,
    load_config,
)

# The generic shim written into ~/.config/gdbrpc/bootstrap.py (decision #13:
# environment specifics live in .env, not in the shim). Raw string: the
# backslash-n escapes below must survive into the generated file verbatim.
SHIM = r'''# Generated by `gdbrpc install` -- generic GDB bootstrap shim.
# Reads ~/.config/gdbrpc/.env, puts the configured site-packages on
# sys.path, then starts the gdbrpc RPC server inside GDB.

import os
import sys

CONFIG_DIR = os.path.expanduser("~/.config/gdbrpc")
ENV_FILE = os.path.join(CONFIG_DIR, ".env")


def _read_env(path):
    values = {}
    if not os.path.exists(path):
        return values
    with open(path) as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            key, _, value = line.partition("=")
            values[key.strip()] = os.path.expanduser(value.strip())
    return values


if sys.version_info < (3, 10):
    sys.stderr.write("[gdbrpc] embedded Python too old: %s\n" % sys.version)
else:
    _env = _read_env(ENV_FILE)
    _site = _env.get("GDBRPC_SITE_PACKAGES", "")
    if not _site or not os.path.isdir(_site):
        sys.stderr.write(
            "[gdbrpc] GDBRPC_SITE_PACKAGES missing or invalid in %s\n"
            % ENV_FILE
        )
    else:
        # addsitedir (not plain sys.path.insert): also processes .pth
        # files, which editable installs rely on.
        import site
        site.addsitedir(_site)
        try:
            import gdbrpc.bootstrap
            gdbrpc.bootstrap.start()
        except Exception:
            import traceback
            sys.stderr.write(
                "[gdbrpc] failed to start:\n" + traceback.format_exc()
            )
'''

ENV_TEMPLATE = """\
# gdbrpc configuration (parsed by the bootstrap shim and gdbrpc itself)

# TCP port of the RPC server (bound to 127.0.0.1 only)
GDBRPC_PORT={port}

# Plugin directory (one .py file per plugin)
GDBRPC_PLUGIN_DIR={plugin_dir}

# Load all discovered plugins immediately at gdb startup (1/true),
# or keep them lazy until loaded via RPC (0/false)
GDBRPC_AUTOLOAD={autoload}

# Bind address of the RPC server (127.0.0.1 = local only, 0.0.0.0 = all
# interfaces, e.g. for docker port publishing — NO AUTH, be careful)
GDBRPC_BIND={bind}

# Line marker color of the dashboard's code view (hex, e.g. #e8c262)
GDBRPC_LINE_MARKER_COLOR={line_marker_color}

# Diff color of changed content in registers/stack/breakpoints/threads
GDBRPC_DIFF_COLOR={diff_color}

# site-packages of the venv that has gdbrpc installed (read by GDB)
GDBRPC_SITE_PACKAGES={site_packages}
"""

PLUGIN_TEMPLATE = '''\
"""{name} plugin."""

import gdb

from gdbrpc.plugin import Plugin, Command, View, Option


class HelloCommand(Command):
    name = "hello"
    description = "Say hello"
    options = [
        Option("who", type="str", required=False, default="world",
               help="Who to greet"),
    ]

    def run(self, opts):
        return {{"greeting": f"Hello, {{opts['who']}}!"}}


class {class_name}(Plugin):
    name = "{name}"
    description = "TODO"
    version = "0.1.0"
    commands = [HelloCommand]
    views = []

    def setup(self):
        pass

    def teardown(self):
        pass
'''

_GDBINIT_LINE = f"source {SHIM_FILE}"


def _upsert_env(env_file, key, value):
    lines = env_file.read_text(encoding="utf-8").splitlines()
    found = False
    for i, line in enumerate(lines):
        stripped = line.strip()
        if stripped.startswith(key + "=") or stripped == key:
            lines[i] = f"{key}={value}"
            found = True
            break
    if not found:
        lines.append(f"{key}={value}")
    env_file.write_text("\n".join(lines) + "\n", encoding="utf-8")


def cmd_install(args):
    CONFIG_DIR.mkdir(parents=True, exist_ok=True)
    Path(os.path.expanduser(str(DEFAULT_PLUGIN_DIR))).mkdir(
        parents=True, exist_ok=True
    )
    site_packages = sysconfig.get_paths()["purelib"]

    # .env — write if missing, otherwise only update our key (never clobber)
    if not ENV_FILE.exists():
        ENV_FILE.write_text(
            ENV_TEMPLATE.format(
                port=DEFAULT_PORT,
                plugin_dir=DEFAULT_PLUGIN_DIR,
                autoload=1,
                bind="127.0.0.1",
                line_marker_color="#e8c262",
                diff_color="#e67e22",
                site_packages=site_packages,
            ),
            encoding="utf-8",
        )
        print(f"wrote {ENV_FILE}")
    else:
        _upsert_env(ENV_FILE, "GDBRPC_SITE_PACKAGES", site_packages)
        # document new keys if the file predates them (never clobber)
        existing = ENV_FILE.read_text(encoding="utf-8")
        if "GDBRPC_AUTOLOAD=" not in existing:
            with open(ENV_FILE, "a", encoding="utf-8") as f:
                f.write(
                    "\n# load all discovered plugins at gdb startup "
                    "(0/false disables)\nGDBRPC_AUTOLOAD=1\n"
                )
        if "GDBRPC_BIND=" not in existing:
            with open(ENV_FILE, "a", encoding="utf-8") as f:
                f.write(
                    "\n# bind address of the RPC server (127.0.0.1 = local "
                    "only; 0.0.0.0 = all interfaces — NO AUTH, be careful)\n"
                    "GDBRPC_BIND=127.0.0.1\n"
                )
        if "GDBRPC_LINE_MARKER_COLOR=" not in existing:
            with open(ENV_FILE, "a", encoding="utf-8") as f:
                f.write(
                    "\n# line marker color of the dashboard's code view "
                    "(hex, e.g. #e8c262)\n"
                    "GDBRPC_LINE_MARKER_COLOR=#e8c262\n"
                )
        if "GDBRPC_DIFF_COLOR=" not in existing:
            with open(ENV_FILE, "a", encoding="utf-8") as f:
                f.write(
                    "\n# diff color of changed content in "
                    "registers/stack/breakpoints/threads\n"
                    "GDBRPC_DIFF_COLOR=#e67e22\n"
                )
        print(f"updated {ENV_FILE}")

    # shim — ours, overwrite when the content changed
    current = SHIM_FILE.read_text(encoding="utf-8") if SHIM_FILE.exists() else None
    if current != SHIM:
        SHIM_FILE.write_text(SHIM, encoding="utf-8")
        print(f"wrote {SHIM_FILE}")
    else:
        print(f"{SHIM_FILE} up to date")

    # .gdbinit — append the source line only if not present (idempotent)
    gdbinit = Path("~/.gdbinit").expanduser()
    content = gdbinit.read_text(encoding="utf-8") if gdbinit.exists() else ""
    if _GDBINIT_LINE not in content:
        with open(gdbinit, "a", encoding="utf-8") as f:
            if content and not content.endswith("\n"):
                f.write("\n")
            f.write(_GDBINIT_LINE + "\n")
        print(f"appended to {gdbinit}: {_GDBINIT_LINE}")
    else:
        print(f"{gdbinit} already sources the shim")

    print(f"\nplugin directory: {DEFAULT_PLUGIN_DIR}")
    print("start gdb and check with: gdbrpc status")


def cmd_status(args):
    failures = []

    def check(ok, label, hint=""):
        mark = "ok  " if ok else "FAIL"
        print(f"[{mark}] {label}")
        if hint:
            print(f"       {hint}")
        if not ok:
            failures.append(label)

    cfg = load_config()
    site_packages = sysconfig.get_paths()["purelib"]

    check(ENV_FILE.exists(), f".env exists ({ENV_FILE})")
    check(bool(cfg.site_packages), ".env sets GDBRPC_SITE_PACKAGES")
    check(
        cfg.site_packages == site_packages,
        ".env GDBRPC_SITE_PACKAGES matches this venv",
        f"env: {cfg.site_packages}\n       venv: {site_packages}",
    )
    import importlib.util
    spec = importlib.util.find_spec("gdbrpc")
    check(
        spec is not None and spec.submodule_search_locations,
        "site-packages provides the gdbrpc package",
        "(checked via import; .env value: " + str(cfg.site_packages) + ")",
    )
    check(SHIM_FILE.exists(), f"shim exists ({SHIM_FILE})")
    check(
        not SHIM_FILE.exists() or SHIM_FILE.read_text() == SHIM,
        "shim is current (re-run: gdbrpc install)",
    )
    check(os.path.isdir(cfg.plugin_dir), f"plugin dir exists ({cfg.plugin_dir})")

    gdbinit = Path("~/.gdbinit").expanduser()
    content = gdbinit.read_text() if gdbinit.exists() else ""
    check(
        _GDBINIT_LINE in content,
        "~/.gdbinit sources the shim",
        f"expected line: {_GDBINIT_LINE}",
    )

    import socket
    s = socket.socket()
    s.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
    try:
        s.bind((cfg.bind, cfg.port))
        in_use = False
    except OSError:
        in_use = True
    finally:
        s.close()
    if in_use:
        # distinguish "a gdbrpc server is live" (fine!) from "something
        # else squats the port" (problem)
        live = False
        try:
            # probe via loopback (works for any bind incl. 0.0.0.0)
            probe_host = "127.0.0.1" if cfg.bind in ("0.0.0.0", "::") \
                else cfg.bind
            c = socket.create_connection((probe_host, cfg.port), timeout=3)
            c.settimeout(3)
            c.sendall(b'{"jsonrpc":"2.0","id":1,"method":"server.info",'
                       b'"params":{}}\n')
            buf = b""
            deadline = time.time() + 3
            while time.time() < deadline and b"\n" not in buf:
                try:
                    chunk = c.recv(4096)
                except socket.timeout:
                    break
                if not chunk:
                    break
                buf += chunk
            c.close()
            live = b"\"protocol\": \"jsonrpc" in buf
        except OSError:
            live = False
        print(f"[info] port {cfg.port} is busy" +
              (" — a live gdbrpc server answers (all good)" if live
               else " — by something that is NOT gdbrpc"))
    else:
        check(True, f"port {cfg.port} is free", "")

    n = 0
    if os.path.isdir(cfg.plugin_dir):
        n = len([p for p in os.listdir(cfg.plugin_dir) if p.endswith(".py")])
    print("\n" + (", ".join(failures) and "FAILED checks: " + ", ".join(failures) or "all checks passed"))
    print("plugins found in plugin dir: {}".format(n))
    return 1 if failures else 0


def cmd_new_plugin(args):
    name = args.name
    if not name.isidentifier():
        print(f"'{name}' is not a valid plugin name", file=sys.stderr)
        return 1
    cfg = load_config()
    plugin_dir = Path(cfg.plugin_dir)
    plugin_dir.mkdir(parents=True, exist_ok=True)
    path = plugin_dir / f"{name}.py"
    if path.exists():
        print(f"{path} already exists", file=sys.stderr)
        return 1
    class_name = "".join(p.capitalize() for p in name.split("_")) + "Plugin"
    path.write_text(
        PLUGIN_TEMPLATE.format(name=name, class_name=class_name),
        encoding="utf-8",
    )
    print(f"wrote {path}")
    return 0


def _parse_params(raw):
    """Parse a JSON object from a CLI argument ('' -> {})."""
    if not raw:
        return {}
    try:
        params = json.loads(raw)
    except Exception as e:
        print(f"invalid params JSON: {e}", file=sys.stderr)
        sys.exit(2)
    if not isinstance(params, dict):
        print("params must be a JSON object", file=sys.stderr)
        sys.exit(2)
    return params


def _bottom_line(text):
    """Write a message into the terminal's last line without scrolling:
    save cursor, jump to the bottom, clear that line, print, restore."""
    import shutil
    width = shutil.get_terminal_size().columns
    text = text[: width - 1]
    sys.stdout.write(
        "\x1b7\x1b[999;1H\x1b[2K" + text + "\x1b8"
    )
    sys.stdout.flush()


def cmd_attach(args):
    """One view per console (tmux arranges the rest): register a view and
    print every pushed update as plain text until Ctrl-C."""
    from .session import Session, render_text

    cfg = load_config()
    params = _parse_params(args.params)

    def on_update(view, trigger, data):
        # A view pane is a screen, not a log: clear the console and fill it
        # with the fresh content (client: "views fill the whole screen").
        print("\033[2J\033[H", flush=True)
        print(f"=== {view} [{trigger}] ===", flush=True)
        print(render_text(data), flush=True)

    def on_error(view, trigger, error, tb):
        # keep the last screen; report the failure in the bottom line
        _bottom_line(f"!!! {view} [{trigger}]: {error}")

    def on_status(text):
        # status never accumulates either — bottom line as well
        _bottom_line(f"[gdbrpc] {text}")

    session = Session(
        cfg.port,
        on_update=on_update, on_error=on_error, on_status=on_status,
    )
    session.register(args.view, params)
    try:
        session.run()
    except KeyboardInterrupt:
        pass
    finally:
        session.stop()
    return 0


def cmd_exec(args):
    """Execute a plugin command over RPC and print the result."""
    from .session import RpcClientError, Session

    cfg = load_config()
    params = _parse_params(args.params)
    session = Session(cfg.port)
    if not session.connect():
        print(
            f"cannot connect to 127.0.0.1:{cfg.port} "
            "(is a gdb with gdbrpc running?)",
            file=sys.stderr,
        )
        return 1
    try:
        result = session.request(
            "commands.execute",
            {"name": args.command_name, "params": params},
        )
    except RpcClientError as e:
        print(f"error {e.code}: {e.message}", file=sys.stderr)
        if e.data:
            print(e.data, file=sys.stderr)
        return 1
    finally:
        session.close()
    print(json.dumps(result, indent=2, default=str))
    return 0


def main(argv=None):
    parser = argparse.ArgumentParser(
        prog="gdbrpc",
        description="plugin framework + JSON-RPC server inside GDB",
    )
    parser.add_argument(
        "--version", action="version", version=f"gdbrpc {__version__}"
    )
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("install", help="install config, shim and .gdbinit hook")
    sub.add_parser("status", help="sanity-check the installation")
    newp = sub.add_parser("new-plugin", help="scaffold a new plugin file")
    newp.add_argument("name")
    att = sub.add_parser(
        "attach", help="attach to a view and print pushed updates (Ctrl-C to exit)"
    )
    att.add_argument("view")
    att.add_argument(
        "--params", help="JSON params for the view registration (optional)"
    )
    exp = sub.add_parser("exec", help="execute a plugin command over RPC")
    exp.add_argument("command_name")
    exp.add_argument("--params", help="JSON params for the command (optional)")
    args = parser.parse_args(argv)
    if args.command == "install":
        return cmd_install(args)
    if args.command == "status":
        return cmd_status(args)
    if args.command == "new-plugin":
        return cmd_new_plugin(args)
    if args.command == "attach":
        return cmd_attach(args)
    if args.command == "exec":
        return cmd_exec(args)
    return 0


if __name__ == "__main__":
    sys.exit(main())